#!/usr/bin/env python3
"""Builds Resources/zh-Hans.lproj/Localizable.strings from Resources/Localization/zh_Hans_*.py.

Keys are written exactly as they appear in Swift source (\\n, \\" escapes), which is also
.strings syntax. `--missing` lists user-facing literals in Sources/QuietGlass without a
translation (identifiers, URLs and interpolations are skipped)."""
import glob, os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
table = {}
for path in sorted(glob.glob(os.path.join(root, "Resources/Localization/zh_Hans_*.py"))):
    scope = {}
    exec(open(path, encoding="utf-8").read(), scope)
    table.update(scope["T"])
# Keys ending in "*" translate the one long source string that starts with that prefix.
prefixes = {k[:-1]: v for k, v in table.items() if k.endswith("*")}

def literals():
    lit = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
    skip = ('systemName:', 'systemImage:', 'forKey:', 'forResource:', 'withExtension:', 'subsystem:',
            'category:', 'named:', 'identifier:', 'Selector((')
    found = {}
    for f in sorted(glob.glob(os.path.join(root, "Sources/*/*.swift"))):
        for n, line in enumerate(open(f, encoding="utf-8"), 1):
            if line.strip().startswith('//') or 'Logger(' in line: continue
            for m in lit.finditer(line):
                s = m.group(1)
                if line[:m.start()].rstrip().endswith(skip) or '\\(' in s: continue
                if not re.search(r'[A-Za-z]', s) or re.fullmatch(r'[a-z][A-Za-z0-9_.\-]*', s): continue
                if re.match(r'^(https?:|x-apple|local\.|com\.apple|public\.|/|--)', s): continue
                found.setdefault(s, f"{os.path.basename(f)}:{n}")
    return found

found = literals()
for prefix, value in prefixes.items():
    matches = [k for k in found if k.startswith(prefix)]
    if len(matches) != 1: sys.exit(f"prefix {prefix[:40]!r} matches {len(matches)} strings")
    table[matches[0]] = value
    del table[prefix + "*"]

if "--missing" in sys.argv:
    for key, where in found.items():
        if key not in table: print(f"{where}\t{key}")
    sys.exit(0)

out = os.path.join(root, "Resources/zh-Hans.lproj")
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "Localizable.strings"), "w", encoding="utf-8") as f:
    f.write("/* Generated by scripts/gen-localization.py. Edit Resources/Localization/zh_Hans_*.py instead. */\n")
    for key in sorted(table):
        f.write(f'"{key}" = "{table[key]}";\n')
print(f"{len(table)} strings -> {out}/Localizable.strings")
